"""Generate court geometry (polylines + keypoints) from spec/court.json.

Outputs:
  generated/court_geometry.json   consumed by Python (handball_court) and TS (src/)

Usage: python packages/court/scripts/generate.py [--check]
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "spec" / "court.json"
OUT = ROOT / "generated" / "court_geometry.json"

Point = tuple[float, float]


def _r(v: float) -> float:
    return round(v, 4)


def _arc(cx: float, cy: float, r: float, a0: float, a1: float, n: int) -> list[Point]:
    return [
        (
            _r(cx + r * math.cos(a0 + (a1 - a0) * i / n)),
            _r(cy + r * math.sin(a0 + (a1 - a0) * i / n)),
        )
        for i in range(n + 1)
    ]


def _d_line(goal_x: float, cy: float, half_goal: float, r: float, n: int, side: int) -> list[Point]:
    """Goal-area style line: quarter circle around each post joined by a straight segment.

    side = +1 for the left goal (x=0, line opens towards +x), -1 for the right goal (x=40).
    """
    lower_post = cy - half_goal
    upper_post = cy + half_goal
    if side == 1:
        lower = _arc(goal_x, lower_post, r, -math.pi / 2, 0.0, n)
        upper = _arc(goal_x, upper_post, r, 0.0, math.pi / 2, n)
    else:
        lower = _arc(goal_x, lower_post, r, -math.pi / 2, -math.pi, n)
        upper = _arc(goal_x, upper_post, r, math.pi, math.pi / 2, n)
    pts = lower + upper
    # clip to court (y within [0, width] handled by caller via filtering)
    return pts


def build(spec: dict[str, Any]) -> dict[str, Any]:
    length = float(spec["length"])
    width = float(spec["width"])
    cy = width / 2
    half_goal = float(spec["goal"]["width"]) / 2
    n = int(spec["arc_samples"])
    r6 = float(spec["goal_area_radius"])
    r9 = float(spec["free_throw_radius"])
    pm = spec["penalty_mark"]
    gk = spec["goalkeeper_restraining_line"]
    sub = spec["substitution_line"]

    def clip(pts: list[Point]) -> list[Point]:
        return [(x, min(max(y, 0.0), width)) for x, y in pts]

    lines: dict[str, Any] = {
        "boundary": [(0.0, 0.0), (length, 0.0), (length, width), (0.0, width), (0.0, 0.0)],
        "center_line": [(length / 2, 0.0), (length / 2, width)],
    }
    keypoints: dict[str, Point] = {
        "corner_bl": (0.0, 0.0),
        "corner_tl": (0.0, width),
        "corner_br": (length, 0.0),
        "corner_tr": (length, width),
        "center": (length / 2, cy),
        "center_bottom": (length / 2, 0.0),
        "center_top": (length / 2, width),
    }
    for name, gx, side in (("left", 0.0, 1), ("right", length, -1)):
        lines[f"goal_area_{name}"] = clip(_d_line(gx, cy, half_goal, r6, n, side))
        lines[f"free_throw_{name}"] = clip(_d_line(gx, cy, half_goal, r9, n, side))
        lines[f"goal_{name}"] = [(gx, cy - half_goal), (gx, cy + half_goal)]
        px = gx + side * float(pm["distance"])
        lines[f"penalty_mark_{name}"] = [(px, cy - pm["length"] / 2), (px, cy + pm["length"] / 2)]
        kx = gx + side * float(gk["distance"])
        lines[f"gk_line_{name}"] = [(kx, cy - gk["length"] / 2), (kx, cy + gk["length"] / 2)]
        keypoints[f"post_{name}_low"] = (gx, cy - half_goal)
        keypoints[f"post_{name}_high"] = (gx, cy + half_goal)
        keypoints[f"goal_area_{name}_low"] = (gx, _r(cy - half_goal - r6))
        keypoints[f"goal_area_{name}_high"] = (gx, _r(cy + half_goal + r6))
        keypoints[f"goal_area_{name}_front_low"] = (_r(gx + side * r6), cy - half_goal)
        keypoints[f"goal_area_{name}_front_high"] = (_r(gx + side * r6), cy + half_goal)
        keypoints[f"free_throw_{name}_front_low"] = (_r(gx + side * r9), cy - half_goal)
        keypoints[f"free_throw_{name}_front_high"] = (_r(gx + side * r9), cy + half_goal)
        keypoints[f"penalty_mark_{name}"] = (px, cy)
    for name, sx in (
        ("left", length / 2 - sub["distance_from_center"]),
        ("right", length / 2 + sub["distance_from_center"]),
    ):
        lines[f"substitution_{name}"] = [(sx, 0.0), (sx, -float(sub["length"]))]

    return {
        "$comment": "GENERATED by packages/court/scripts/generate.py. Do not edit.",
        "sport": spec["sport"],
        "version": spec["version"],
        "length": length,
        "width": width,
        "goal": spec["goal"],
        "goal_area_radius": r6,
        "free_throw_radius": r9,
        "dashed_lines": [k for k in lines if k.startswith("free_throw_")],
        "lines": {k: [list(p) for p in v] for k, v in lines.items()},
        "keypoints": {k: list(v) for k, v in keypoints.items()},
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated file is stale")
    args = parser.parse_args()
    spec = json.loads(SPEC.read_text())
    rendered = json.dumps(build(spec), indent=2) + "\n"
    if args.check:
        if not OUT.exists() or OUT.read_text() != rendered:
            print("court geometry is stale, run `make court`", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(rendered)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
