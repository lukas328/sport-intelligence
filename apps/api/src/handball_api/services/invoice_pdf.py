"""Invoice PDF with Swiss QR bill payment part (addendum 01, 4.10).

Mandatory content (CH): creditor name and address, recipient, invoice number and date, service and
period, amounts, VAT rate and amount with UID when VAT registered, payment term. The payment part is
generated by `qrbill` (SIX implementation guidelines) and placed at the bottom of the page.
"""

