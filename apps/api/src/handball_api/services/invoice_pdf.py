QR_LANG = {"de-CH": "de", "fr": "fr", "en": "en"}


def chf(cents: int) -> str:
    return f"{cents // 100:,}.{cents % 100:02d}".replace(",", "'")


def _d(v: date) -> str:
    return v.strftime("%d.%m.%Y")


def qr_bill(creditor: dict[str, str], iban: str, inv: dict[str, Any], lang: str) -> QRBill:
    r = inv["recipient"]
    return QRBill(
        account=iban,
        creditor=creditor,
        debtor={k: r[k] for k in ("name", "street", "pcode", "city", "country") if r.get(k)},
        amount=f"{inv['total_cents'] / 100:.2f}",
        currency="CHF",
        reference_number=inv["reference"],
        additional_information=inv["number"],
        language=QR_LANG.get(lang, "de"),
    )


def render(
    lang: str,
    creditor: dict[str, str],
    iban: str,
    uid: str | None,
    inv: dict[str, Any],
    payment_days: int,
    kind: str = "invoice",
) -> bytes:
    t = TEXT.get(lang, TEXT["de-CH"])
    buf = io.BytesIO()
    c = Canvas(buf, pagesize=A4)
    w, h = A4
    c.setTitle(f"{t[kind]} {inv['number']}")
    c.setFont("Helvetica-Bold", 11)
    c.drawString(20 * mm, h - 20 * mm, creditor["name"])
    c.setFont("Helvetica", 9)
    c.drawString(
        20 * mm, h - 25 * mm, f"{creditor['street']}, {creditor['pcode']} {creditor['city']}"
    )
    if uid:
        c.drawString(20 * mm, h - 30 * mm, t["uid"].format(uid=uid))
    # recipient in the window of a C5 envelope (right)
    r = inv["recipient"]
    y = h - 52 * mm
    c.setFont("Helvetica", 10)
    for line in [
        r.get("name"),
        r.get("attention"),
        r.get("street"),
        f"{r.get('pcode', '')} {r.get('city', '')}".strip(),
    ]:
        if line:
            c.drawString(118 * mm, y, str(line))
            y -= 5 * mm
    c.setFont("Helvetica-Bold", 15)
    c.drawString(20 * mm, h - 85 * mm, f"{t[kind]} {inv['number']}")
    c.setFont("Helvetica", 9.5)
    y = h - 93 * mm
    meta = [
        (t["number"], inv["number"]),
        (t["date"], _d(inv["issued_on"])),
        (t["due"], _d(inv["due_date"])),
    ]
    if inv.get("period_start") and inv.get("period_end"):
        meta.append((t["period"], f"{_d(inv['period_start'])} - {_d(inv['period_end'])}"))
    for k, v in meta:
        c.drawString(20 * mm, y, k)
        c.drawString(65 * mm, y, v)
        y -= 5 * mm
    y -= 4 * mm
    c.line(20 * mm, y, w - 20 * mm, y)
    y -= 6 * mm
    for line in inv["lines"]:
        c.drawString(20 * mm, y, str(line["text"]))
        c.drawRightString(w - 20 * mm, y, f"CHF {chf(int(line['cents']))}")
        y -= 5 * mm
    rows = [(t["net"], inv["net_cents"])]
    if inv["discount_cents"]:
        rows.append(
            (
                t["discount"] + (f" ({inv['voucher_code']})" if inv.get("voucher_code") else ""),
                -inv["discount_cents"],
            )
        )
    if inv["vat_rate_bp"]:
        rows.append((t["vat"].format(rate=f"{inv['vat_rate_bp'] / 100:.1f}"), inv["vat_cents"]))
    y -= 2 * mm
    for k, v in rows:
        c.drawString(110 * mm, y, k)
        c.drawRightString(w - 20 * mm, y, ("-" if v < 0 else "") + f"CHF {chf(abs(v))}")
        y -= 5 * mm
    c.setFont("Helvetica-Bold", 10.5)
    c.drawString(110 * mm, y, t["total"])
    c.drawRightString(w - 20 * mm, y, f"CHF {chf(inv['total_cents'])}")
    c.setFont("Helvetica", 9)
    y -= 9 * mm
    if not inv["vat_rate_bp"]:
        c.drawString(20 * mm, y, t["no_vat"])
        y -= 5 * mm
    c.drawString(20 * mm, y, t["terms"].format(days=payment_days))
    # payment part: 210 x 105 mm at the bottom of the page
    bill = qr_bill(creditor, iban, inv, lang)
    with tempfile.TemporaryDirectory() as tmp:
        svg = Path(tmp) / "qr.svg"
        with svg.open("w", encoding="utf-8") as f:
            bill.as_svg(f)
        drawing = svg2rlg(str(svg))
        assert drawing is not None
        sx = (210 * mm) / drawing.width
        drawing.scale(sx, sx)
        drawing.width *= sx
        drawing.height *= sx
        renderPDF.draw(drawing, c, 0, 0)
    c.showPage()
    c.save()
    return buf.getvalue()
