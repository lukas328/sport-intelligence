export const DICTS: Record<string, Dict> = { "de-CH": de, fr, en };

export function translator(locale: string | undefined) {
  const dict = DICTS[locale ?? ""] ?? de;
  return (key: Key, vars: Record<string, string | number> = {}) =>
    dict[key].replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}
