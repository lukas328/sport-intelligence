"""Event baseline evaluation (addendum 01, A3) on synthetic matches with scripted goals, throw-offs
and a side change. Runs the full pipeline (rendering, detection, tracking, teams) and compares the
detected events with the ground truth. Writes docs/perf/events-eval.md.

Real matches (TeamTrack, own clubs) are added to the golden set once available (Q-ADD-6).
"""

from __future__ import annotations

import argparse
import tempfile
import time
from pathlib import Path

from handball_vision.events import score
from handball_vision.pipeline import analyse_video
from handball_vision.synthetic import SyntheticConfig, SyntheticMatch

TOLERANCE_MS = {"throw_off": 1500, "goal": 3000, "side_change": 20_000, "possession_change": 3000}
TARGETS = {"goal": (0.8, 0.7), "throw_off": (0.9, 0.8), "possession_change": (0.8, 0.8)}


def run(
    seconds: float, seed: int, workdir: Path
) -> tuple[dict[str, dict[str, float]], float, dict[str, int]]:
    cfg = SyntheticConfig(
        seconds=seconds, seed=seed, restarts=True, phase_s=20, side_change_s=seconds / 2 // 20 * 20
    )
    match = SyntheticMatch(cfg)
    video = workdir / f"events-{seed}.mp4"
    match.write(video)
    k = cfg.kits
    t0 = time.perf_counter()
    res = analyse_video(
        video,
        {
            "home": k.home,
            "home_gk": k.home_gk,
            "away": k.away,
            "away_gk": k.away_gk,
            "referee": k.referee,
        },
    )
    found = res.detect_events()
    elapsed = time.perf_counter() - t0
    truth = match.events()
    scores = {kind: score(found.events, truth, kind, tol) for kind, tol in TOLERANCE_MS.items()}
    labels: dict[str, int] = {}
    for v in res.teams.values():
        labels[str(v["label"])] = labels.get(str(v["label"]), 0) + 1
    return scores, elapsed, labels


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seconds", type=float, default=200)
    ap.add_argument("--seeds", type=int, nargs="+", default=[7, 11])
    ap.add_argument("--out", type=Path, default=Path("docs/perf/events-eval.md"))
    args = ap.parse_args()
    rows = []
    with tempfile.TemporaryDirectory() as tmp:
        for seed in args.seeds:
            scores, elapsed, labels = run(args.seconds, seed, Path(tmp))
            print(seed, scores, round(elapsed, 1), labels, flush=True)
            rows.append((seed, scores, elapsed))
    lines = [
        "| seed | event | truth | found | precision | recall | target (P/R) |",
        "|---|---|---|---|---|---|---|",
    ]
    for seed, scores, _ in rows:
        for kind, s in scores.items():
            tgt = TARGETS.get(kind)
            mark = ""
            if tgt:
                ok = s["precision"] >= tgt[0] and s["recall"] >= tgt[1]
                mark = f"{tgt[0]}/{tgt[1]} {'✓' if ok else '✗'}"
            lines.append(
                f"| {seed} | {kind} | {int(s['truth'])} | {int(s['found'])} | {s['precision']:.2f} | {s['recall']:.2f} | {mark} |"
            )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(
        "# Event baseline evaluation (synthetic)\n\nGenerated by `ml/eval/events.py`: full pipeline on synthetic "
        f"matches of {args.seconds:.0f} s with scripted goals, throw-offs and one side change (25 fps, "
        "1280x720, CPU). Goals are inferred from the throw-off that follows; a goal right before half-time "
        "cannot be inferred this way (the next throw-off opens the half). Shots, saves and turnovers need "
        "the ball and are not part of this baseline. Real footage is pending (OPEN_QUESTIONS Q-ADD-6).\n\n"
        + "\n".join(lines)
        + "\n"
    )


if __name__ == "__main__":
    main()
