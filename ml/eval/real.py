"""Real-video evaluation (Q-DATA-1): run the analysis on the real test videos in data/videos/.

Real clips have no ground truth yet (Q-DATA-3), so this measures health, not accuracy:

1. Whole-clip calibration as the pipeline does it (fixed-camera assumption): ok or the reason it fails.
2. Per-frame calibration on frames spread across the clip: share of frames where the court is found.
   With a panning camera this is what matters, a single homography cannot fit the whole clip.
3. If the whole-clip calibration works: the full analysis on the first --seconds, with detections per
   frame, track fragmentation (raw vs. stitched tracks), team split and speed.

Videos come from ml/eval/golden_set/manifest.json and are expected under data/videos/ (`make testdata`).
Entries without a local file are listed as missing. Debug images (line masks) go to data/eval-real/.

    uv run python ml/eval/real.py [--seconds 30] [--frames 24] [--out docs/perf/eval-real.md] [ID ...]
"""

from __future__ import annotations

import argparse
import json
import time
from collections import Counter
from pathlib import Path
from typing import Any

import cv2
import numpy as np

from handball_vision.calibration import CalibrationError, calibrate_frames, line_mask
from handball_vision.pipeline import _open, analyse_video, sample_frames

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "ml" / "eval" / "golden_set" / "manifest.json"
VIDEO_DIR = ROOT / "data" / "videos"
DEBUG_DIR = ROOT / "data" / "eval-real"


def hex_to_bgr(value: str) -> tuple[int, int, int]:
    v = value.lstrip("#")
    r, g, b = (int(v[i : i + 2], 16) for i in (0, 2, 4))
    return (b, g, r)


def calibrate_each(frames: list[Any]) -> tuple[int, Counter[str], list[float]]:
    ok = 0
    reasons: Counter[str] = Counter()
    confidences: list[float] = []
    for frame in frames:
        try:
            c = calibrate_frames([frame])
        except CalibrationError as e:
            reasons[str(e).split(" (")[0]] += 1
            continue
        ok += 1
        confidences.append(c.confidence)
    return ok, reasons, confidences


def write_debug(entry_id: str, frames: list[Any]) -> None:
    DEBUG_DIR.mkdir(parents=True, exist_ok=True)
    frame = frames[len(frames) // 2]
    mask = line_mask(frame)
    overlay = frame.copy()
    overlay[mask > 0] = (0, 0, 255)
    cv2.imwrite(str(DEBUG_DIR / f"{entry_id}-lines.jpg"), np.hstack([frame, overlay]))


def evaluate(entry: dict[str, Any], path: Path, seconds: float, n_frames: int) -> dict[str, Any]:
    row: dict[str, Any] = {"id": entry["id"], "camera": entry.get("camera", "unknown")}
    frames = sample_frames(path, n_frames)
    write_debug(entry["id"], frames)

    try:
        calib = calibrate_frames(frames[::2])
        row["clip_calibration"] = (
            f"ok (conf {calib.confidence:.2f}, {calib.reprojection_px:.1f} px)"
        )
    except CalibrationError as e:
        calib = None
        row["clip_calibration"] = f"failed: {e}"

    ok, reasons, conf = calibrate_each(frames)
    row["frame_calibration"] = f"{ok}/{len(frames)}"
    row["frame_calibration_share"] = ok / max(1, len(frames))
    row["frame_failures"] = dict(reasons.most_common())
    row["frame_confidence"] = round(float(np.mean(conf)), 2) if conf else None

    if calib is None:
        row["analysis"] = "skipped (no calibration)"
        return row
    kits = {k: hex_to_bgr(v) for k, v in (entry.get("kits") or {}).items()}
    if len(kits) != 2:
        row["analysis"] = "skipped (no kits in manifest)"
        return row
    container, _, fps, _ = _open(path)
    container.close()
    t0 = time.perf_counter()
    res = analyse_video(path, kits, calibration=calib, max_frames=int(seconds * fps))
    wall = time.perf_counter() - t0
    labels = Counter(str(t["label"]) for t in res.teams.values())
    row["analysis"] = "ok"
    row["detections_per_frame"] = round(res.detections_per_frame, 1)
    row["raw_tracks"] = res.extra["raw_tracks"]
    row["tracks"] = res.extra["tracks"]
    row["team_split"] = dict(labels)
    row["realtime_factor"] = round(wall / max(1e-9, res.frames / res.fps), 2)
    return row


def to_markdown(rows: list[dict[str, Any]], seconds: float, n_frames: int) -> str:
    lines = [
        "# Real-video evaluation",
        "",
        f"Generated by `ml/eval/real.py` ({n_frames} sampled frames per clip, analysis on the first"
        f" {seconds:.0f} s). No ground truth yet (Q-DATA-3): these are health checks, not accuracy.",
        "",
        "| Clip | Camera | Clip calibration | Frames calibrated | Frame failures | Analysis |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        if r.get("missing"):
            lines.append(f"| {r['id']} | {r['camera']} | missing locally | | | |")
            continue
        fails = ", ".join(f"{k} x{v}" for k, v in r["frame_failures"].items()) or "-"
        analysis = r["analysis"]
        if analysis == "ok":
            analysis = (
                f"{r['detections_per_frame']} det/frame, {r['raw_tracks']}→{r['tracks']} tracks,"
                f" teams {r['team_split']}, {r['realtime_factor']}x realtime"
            )
        lines.append(
            f"| {r['id']} | {r['camera']} | {r['clip_calibration']} | {r['frame_calibration']}"
            f" | {fails} | {analysis} |"
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("ids", nargs="*")
    ap.add_argument("--seconds", type=float, default=30.0)
    ap.add_argument("--frames", type=int, default=24)
    ap.add_argument("--out", type=Path)
    ap.add_argument("--json", type=Path)
    args = ap.parse_args()

    entries = json.loads(MANIFEST.read_text(encoding="utf-8"))["matches"]
    if args.ids:
        entries = [e for e in entries if e["id"] in args.ids]
    if not entries:
        print("no entries in the manifest (see data/README.md)")
        return 1
    rows = []
    for entry in entries:
        path = VIDEO_DIR / Path(entry["key"]).name
        if not path.exists():
            rows.append({"id": entry["id"], "camera": entry.get("camera"), "missing": True})
            print(f"missing     {entry['id']} (run make testdata)")
            continue
        print(f"evaluate    {entry['id']}", flush=True)
        rows.append(evaluate(entry, path, args.seconds, args.frames))
    md = to_markdown(rows, args.seconds, args.frames)
    print(md)
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(md, encoding="utf-8")
    if args.json:
        args.json.write_text(json.dumps(rows, indent=2), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
