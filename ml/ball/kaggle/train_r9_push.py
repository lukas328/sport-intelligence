"""Round 9 of the 3-frame ball net: round 8 (train_r8_push.py) with Claude's training clip labels.

The labels come from ml/gold/train_labels_r9.py: the owner's 1000 peaks of round 8 plus the ball
points Claude placed in the training clips (no owner rough track; tiers sure / track / confirmed,
98 % within 12 px on the pilot gold clips) and, per labelled frame, the net's strongest wrong peak
as a hard negative. Same tile cutting, validation split and batch groups as round 8; starts from
ball_r8.pt. Judged on the gold standard (ml/gold/eval_ball.py), not only on test set 2.

    python ml/ball/kaggle/train_r9_push.py LABELS_JSON WORKDIR   # then: kaggle kernels push -p WORKDIR
"""
import json, subprocess, sys
from pathlib import Path

here = Path(__file__).resolve().parent
work = Path(sys.argv[2]); work.mkdir(parents=True, exist_ok=True)
subprocess.run([sys.executable, str(here / "train_r8_push.py"), sys.argv[1], str(work)], check=True)
src = (work / "kaggle_r8.py").read_text()
for a, b in (("ball_r8.pt", "ball_r9.pt"), ("r8_out.zip", "r9_out.zip"), ("r8_stats.json", "r9_stats.json"),
             ("r8_review_", "r9_review_"), ("owl_tiles_r8.zip", "owl_tiles_r9.zip")):
    src = src.replace(a, b)
old = 'INIT = (glob.glob(INP + "/**/ball_r7.pt", recursive=True)'
assert src.count(old) == 1, "init anchor"
src = src.replace(old, 'INIT = (glob.glob(INP + "/**/ball_r8.pt", recursive=True) or glob.glob(INP + "/**/ball_r7.pt", recursive=True)')
src = src.replace('"""Round 8: generated by', '"""Round 9 (train_r9_push.py over round 8): generated by', 1)
(work / "kaggle_r8.py").unlink()
(work / "kaggle_r9.py").write_text(src)
meta = json.loads((work / "kernel-metadata.json").read_text())
labels = json.load(open(sys.argv[1]))
meta["dataset_sources"] = sorted(set(meta["dataset_sources"]) | {"lukasde1000/" + l["video"].split("/")[0] for l in labels})
meta.update(id="lukasde1000/handball-ball-r9", title="handball ball r9", code_file="kaggle_r9.py")
(work / "kernel-metadata.json").write_text(json.dumps(meta, indent=1))
print(work, "round 9 kernel written")
